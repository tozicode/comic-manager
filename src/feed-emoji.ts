/** 知らない番号（新しい版の一覧）は ❔ で出す */
export function feedEmoji(i: number): string {
  return FEED_EMOJI[i] ?? "❔";
}

/** 送り手の絵文字 2 つを並べたもの（「🐧🍙」） */
export function feedWho(emoji: readonly [number, number] | readonly number[]): string {
  return `${feedEmoji(emoji[0])}${feedEmoji(emoji[1])}`;
}
